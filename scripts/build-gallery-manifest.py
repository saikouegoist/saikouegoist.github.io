"""Build the homepage gallery manifest from images/.

Scans the `images/` folder for supported image files and writes
`data/gallery.js` as `window.SITE_GALLERY = [...]`.

AUTO-GENERATED output -- do not edit `data/gallery.js` by hand.
Just add/remove images in `images/` and re-run:

    python scripts/build-gallery-manifest.py

A GitHub Action (.github/workflows/gallery-manifest.yml) re-runs this
on every push that touches `images/` so github.io stays in sync with
zero manual list maintenance.
"""

import json
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IMAGES_DIR = ROOT / "images"
OUTPUT_JS = ROOT / "data" / "gallery.js"

SUPPORTED_EXTS = {".png", ".jpg", ".jpeg", ".gif", ".webp"}


def main():
    try:
        candidates = list(IMAGES_DIR.iterdir())
    except FileNotFoundError:
        candidates = []
    files = sorted(
        (p for p in candidates if p.is_file() and p.suffix.lower() in SUPPORTED_EXTS),
        key=lambda p: p.name.lower(),
    )
    paths = ["images/" + urllib.parse.quote(p.name, safe="") for p in files]

    lines = [
        "/**",
        " * MEOWKING - Homepage Gallery Manifest (AUTO-GENERATED)",
        " * -------------------------------------------------------------",
        " * Do NOT edit by hand. Generated by scripts/build-gallery-manifest.py",
        " * from the contents of images/. Add/remove images there and re-run",
        " * the script (or push -- the gallery-manifest workflow does it).",
        " */",
        "",
        "window.SITE_GALLERY = [",
    ]
    for path in paths:
        lines.append("  " + json.dumps(path) + ",")
    lines.append("];")
    lines.append("")

    OUTPUT_JS.write_text("\n".join(lines), encoding="utf-8")
    print(f"gallery manifest: {len(paths)} image(s) -> {OUTPUT_JS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
